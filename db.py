"""Banco de dados do Artlog: SQLite no seu computador, PostgreSQL em produção.

Qual banco é usado:
- Sem a variável DATABASE_URL: SQLite, no arquivo artlog.db (ou no caminho de ARTLOG_DB).
  É o jeito mais simples de desenvolver: não precisa instalar nem configurar nada.
- Com DATABASE_URL=postgresql://...: PostgreSQL (por exemplo, o Neon). É o que vai no
  Render, porque lá os arquivos criados pelo site somem a cada reinício.

O resto do código não precisa saber qual banco está em uso. Ele sempre:
- escreve os SQL com `?` no lugar dos valores (aqui vira %s no PostgreSQL);
- lê as colunas pelo nome, row["coluna"] (ou pela posição, row[0]);
- usa `with db:` para gravar (confirma no fim; se der erro, desfaz tudo).
"""
from __future__ import annotations

import os
import re
import sqlite3
import threading
import unicodedata
from contextlib import closing
from pathlib import Path
from typing import Any, Iterable, Iterator

BASE_DIR = Path(__file__).resolve().parent
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
IS_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))
DB_PATH = Path(os.environ.get("ARTLOG_DB", BASE_DIR / "artlog.db"))

if IS_POSTGRES:
    import psycopg
    from psycopg_pool import ConnectionPool

    IntegrityError: type[Exception] = psycopg.IntegrityError
else:
    IntegrityError = sqlite3.IntegrityError


# ---------------------------------------------------------------------------
# Esquema (o mesmo para os dois bancos)
# ---------------------------------------------------------------------------
# Só três coisas mudam de um banco para o outro:
#   {pk}     id que aumenta sozinho
#   {blob}   dados binários (a foto de perfil)
#   {bigint} números grandes (datas em segundos, versão da foto em milissegundos)
TYPES = {
    "sqlite": {"pk": "INTEGER PRIMARY KEY AUTOINCREMENT", "blob": "BLOB", "bigint": "INTEGER"},
    "postgres": {"pk": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "blob": "BYTEA", "bigint": "BIGINT"},
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id             {pk},
    username       TEXT NOT NULL UNIQUE,
    email          TEXT NOT NULL UNIQUE,
    password_hash  TEXT NOT NULL,
    created_at     {bigint} NOT NULL,
    display_name   TEXT NOT NULL DEFAULT '',
    bio            TEXT NOT NULL DEFAULT '',
    avatar_version {bigint},
    name_key       TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id    {bigint} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at {bigint} NOT NULL,
    expires_at {bigint} NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

-- Foto de perfil (uma por usuário), guardada no próprio banco.
CREATE TABLE IF NOT EXISTS avatars (
    user_id      {bigint} PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    content_type TEXT NOT NULL,
    data         {blob} NOT NULL
);

-- Top 5 de obras. Guarda uma cópia da obra (título, imagem...) para o perfil
-- aparecer sem precisar consultar os museus de novo.
CREATE TABLE IF NOT EXISTS top_artworks (
    user_id    {bigint} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    position   INTEGER NOT NULL CHECK (position BETWEEN 1 AND 5),
    artwork_id TEXT NOT NULL,
    artwork    TEXT NOT NULL,
    PRIMARY KEY (user_id, position),
    UNIQUE (user_id, artwork_id)
);

-- Curadorias: listas de obras com nome, públicas ou privadas.
CREATE TABLE IF NOT EXISTS curations (
    id          {pk},
    user_id     {bigint} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    is_public   INTEGER NOT NULL DEFAULT 1,
    created_at  {bigint} NOT NULL,
    updated_at  {bigint} NOT NULL
);
CREATE INDEX IF NOT EXISTS curations_user ON curations(user_id);
CREATE INDEX IF NOT EXISTS curations_public_updated ON curations(is_public, updated_at);

-- Obras de cada curadoria, com a nota e a data (AAAA-MM-DD) em que a pessoa viu a obra.
CREATE TABLE IF NOT EXISTS curation_items (
    curation_id {bigint} NOT NULL REFERENCES curations(id) ON DELETE CASCADE,
    artwork_id  TEXT NOT NULL,
    artwork     TEXT NOT NULL,
    position    INTEGER NOT NULL,
    note        TEXT NOT NULL DEFAULT '',
    seen        TEXT NOT NULL DEFAULT '',
    added_at    {bigint} NOT NULL,
    PRIMARY KEY (curation_id, artwork_id)
);

-- Uma nota (1 a 5 estrelas) por pessoa em cada curadoria.
CREATE TABLE IF NOT EXISTS curation_ratings (
    curation_id {bigint} NOT NULL REFERENCES curations(id) ON DELETE CASCADE,
    user_id     {bigint} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    stars       INTEGER NOT NULL CHECK (stars BETWEEN 1 AND 5),
    rated_at    {bigint} NOT NULL,
    PRIMARY KEY (curation_id, user_id)
);

-- Quem segue quem.
CREATE TABLE IF NOT EXISTS follows (
    follower_id {bigint} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    followee_id {bigint} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at  {bigint} NOT NULL,
    PRIMARY KEY (follower_id, followee_id),
    CHECK (follower_id != followee_id)
);
CREATE INDEX IF NOT EXISTS follows_followee ON follows(followee_id);
"""

# Colunas que entraram depois da primeira versão. Bancos antigos ganham as colunas
# automaticamente ao iniciar, sem perder as contas que já existem.
USER_COLUMNS = {
    "display_name": "TEXT NOT NULL DEFAULT ''",
    "bio": "TEXT NOT NULL DEFAULT ''",
    "avatar_version": "{bigint}",
    # Nome + @usuário sem acentos e em minúsculas, para a busca de pessoas
    # ("joao" encontra "João"). É feito em Python para funcionar igual nos dois bancos.
    "name_key": "TEXT NOT NULL DEFAULT ''",
}


def search_key(*parts: str | None) -> str:
    """'João Burgos', 'joao_b' -> 'joao burgos joao_b' (sem acento, minúsculo, espaços simples)."""
    text = " ".join(part for part in parts if part)
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return " ".join(text.casefold().split())


def _fill_name_keys(conn: Any, placeholder: str) -> None:
    """Contas criadas antes da busca de pessoas: calcula o name_key que falta."""
    rows = conn.execute("SELECT id, username, display_name FROM users WHERE name_key = ''").fetchall()
    for row in rows:
        conn.execute(
            f"UPDATE users SET name_key = {placeholder} WHERE id = {placeholder}",
            (search_key(row["display_name"], row["username"]), row["id"]),
        )


def _statements(kind: str) -> list[str]:
    sql = SCHEMA.format(**TYPES[kind])
    sql = "\n".join(line for line in sql.splitlines() if not line.strip().startswith("--"))
    return [stmt.strip() for stmt in sql.split(";") if stmt.strip()]


# ---------------------------------------------------------------------------
# Linhas: acesso por nome (row["id"]) ou por posição (row[0]), nos dois bancos
# ---------------------------------------------------------------------------
class Row(dict):
    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _pg_row_factory(cursor: Any):
    names = [column.name for column in cursor.description or []]
    return lambda values: Row(zip(names, values))


# ---------------------------------------------------------------------------
# A conexão que as rotas recebem
# ---------------------------------------------------------------------------
class Database:
    """Mesma forma de usar para SQLite e PostgreSQL."""

    def __init__(self, conn: Any) -> None:
        self.conn = conn

    @staticmethod
    def _sql(sql: str) -> str:
        return sql.replace("?", "%s") if IS_POSTGRES else sql

    def execute(self, sql: str, params: Iterable[Any] = ()) -> Any:
        return self.conn.execute(self._sql(sql), tuple(params))

    def executemany(self, sql: str, rows: Iterable[Iterable[Any]]) -> None:
        rows = [tuple(row) for row in rows]
        if not rows:
            return
        if IS_POSTGRES:
            with self.conn.cursor() as cur:
                cur.executemany(self._sql(sql), rows)
        else:
            self.conn.executemany(sql, rows)

    # `with db:` grava tudo junto no fim; se der erro no meio, desfaz tudo.
    def __enter__(self) -> "Database":
        return self

    def __exit__(self, exc_type: Any, exc: Any, tb: Any) -> bool:
        if exc_type is None:
            self.conn.commit()
        else:
            self.conn.rollback()
        return False


def _sqlite_connect() -> sqlite3.Connection:
    # check_same_thread=False: cada conexão é usada por uma só requisição, mas o FastAPI
    # pode abri-la numa thread e usá-la em outra (rotas async, como o envio da foto).
    conn = sqlite3.connect(DB_PATH, timeout=10, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


# No PostgreSQL, abrir uma conexão nova a cada requisição é lento (tem criptografia,
# e o banco fica em outro servidor). Um "pool" mantém algumas conexões abertas e reaproveita.
_pool: Any = None
_pool_lock = threading.Lock()


def _get_pool() -> Any:
    global _pool
    with _pool_lock:
        if _pool is None:
            _pool = ConnectionPool(
                DATABASE_URL,
                min_size=1,
                max_size=int(os.environ.get("DB_POOL_SIZE", "5")),
                # prepare_threshold=None: não usa "prepared statements", que dão erro
                # quando o banco está atrás de um PgBouncer (como o endereço "-pooler" do Neon).
                kwargs={"row_factory": _pg_row_factory, "prepare_threshold": None},
                # O Neon gratuito "dorme" sem uso e derruba as conexões abertas:
                # testa cada conexão antes de entregar e fecha as paradas há muito tempo.
                check=ConnectionPool.check_connection,
                max_idle=240,
                name="artlog",
                open=True,
            )
    return _pool


def get_db() -> Iterator[Database]:
    """Uma conexão por requisição (as rotas rodam em várias threads)."""
    if IS_POSTGRES:
        with _get_pool().connection() as conn:
            yield Database(conn)
    else:
        conn = _sqlite_connect()
        try:
            yield Database(conn)
        finally:
            conn.close()


def init_db() -> None:
    """Cria as tabelas que faltam. Pode rodar sempre: não apaga nada."""
    if IS_POSTGRES:
        with _get_pool().connection() as conn:
            # Trava simples: se dois processos iniciarem juntos, um espera o outro.
            conn.execute("SELECT pg_advisory_xact_lock(727274)")
            for stmt in _statements("postgres"):
                conn.execute(stmt)
            for name, definition in USER_COLUMNS.items():
                conn.execute(f"ALTER TABLE users ADD COLUMN IF NOT EXISTS {name} {definition.format(**TYPES['postgres'])}")
            _fill_name_keys(conn, "%s")
        return

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    with closing(_sqlite_connect()) as conn:
        # Bancos antigos: as colunas novas de users entram antes dos índices e tabelas novas.
        has_users = conn.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'users'").fetchone()
        if has_users:
            existing = {row["name"] for row in conn.execute("PRAGMA table_info(users)")}
            for name, definition in USER_COLUMNS.items():
                if name not in existing:
                    conn.execute(f"ALTER TABLE users ADD COLUMN {name} {definition.format(**TYPES['sqlite'])}")
        for stmt in _statements("sqlite"):
            conn.execute(stmt)
        _fill_name_keys(conn, "?")
        conn.commit()


def describe() -> str:
    """Para o log de inicialização: qual banco está em uso (sem mostrar a senha)."""
    if IS_POSTGRES:
        return "PostgreSQL (" + re.sub(r"//[^@/]*@", "//***@", DATABASE_URL).split("?")[0] + ")"
    return f"SQLite ({DB_PATH})"
